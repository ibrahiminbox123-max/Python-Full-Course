number = int(input("Enter Your Marks: "))

if number >= 90 and number <= 100:
    print("Your Grade Is A+")

elif number >= 80:
    print("Your Grade Is A")

elif number >= 70:
    print("Your Grade Is B")

elif number >= 60:
    print("Your Grade Is C")

elif number >= 50:
    print("Your Grade Is D")

else:
    print("You Are Fail")